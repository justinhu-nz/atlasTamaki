#!/usr/bin/env python3
"""Generate content-addressed display images; originals remain available on demand.
Run after editing image files: python3 -m pip install Pillow && python3 scripts/optimize-images.py
"""
import hashlib
import json
from pathlib import Path
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
SIZES = {"thumb": (320, 76), "display": (960, 82), "map": (2048, 86)}


def main():
    data = json.loads((ROOT / "ideas.js").read_text().split("window.ATLAS =", 1)[1].strip().removesuffix(";"))
    output = ROOT / "images" / "optimized"
    output.mkdir(exist_ok=True)
    manifest, original_bytes, variant_bytes = {}, 0, {key: 0 for key in SIZES}
    for file in sorted({im["file"] for idea in data["ideas"] for im in idea["images"] if im.get("file", "").startswith("images/")}):
        source = ROOT / file
        original_bytes += source.stat().st_size
        # Version the recipe as well as the source so URLs change whenever output changes.
        digest = hashlib.sha256(source.read_bytes() + b"atlas-webp-v1-320-960-2048").hexdigest()[:16]
        with Image.open(source) as raw:
            image = ImageOps.exif_transpose(raw).convert("RGBA" if "A" in raw.getbands() else "RGB")
            entry = {"width": image.width, "height": image.height}
            for key, (size, quality) in SIZES.items():
                target = output / f"{digest}-{size}.webp"
                if not target.exists():
                    variant = image.copy()
                    variant.thumbnail((size, size), Image.Resampling.LANCZOS)
                    variant.save(target, "WEBP", quality=quality, method=6)
                entry[key] = target.relative_to(ROOT).as_posix()
                variant_bytes[key] += target.stat().st_size
            manifest[file] = entry
    (ROOT / "image-manifest.js").write_text("// Generated by scripts/optimize-images.py; do not edit.\nwindow.ATLAS_IMAGES = " + json.dumps(manifest, ensure_ascii=False, separators=(",", ":")) + ";\n")
    print(json.dumps({"files": len(manifest), "original_bytes": original_bytes, "variant_bytes": variant_bytes}, indent=2))


if __name__ == "__main__":
    main()
